import { signRequest } from "./sigv4";

/**
 * Where uploaded images are kept. One interface, three backends, chosen from what is configured:
 *
 *   r2-binding   Cloudflare Worker with an R2 bucket bound as IMAGES (wrangler.jsonc "r2_buckets"). Used in production on Cloudflare.
 *   r2-s3        R2 through its S3-compatible API, with R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY and R2_BUCKET.
 *                Used on Vercel and when running on a PC against the real bucket.
 *   none         Nothing configured. Uploads are refused: images are never stored anywhere except R2.
 *
 * Public addresses are always IMAGE_PUBLIC_BASE_URL plus the object key (default https://images.vierapparatus.com, the domain the bucket is served on).
 * Secrets are read on the server only and are never sent to the browser.
 */

export type R2BucketLike = {
  put(key: string, value: ArrayBuffer | Uint8Array, options?: { httpMetadata?: { contentType?: string; cacheControl?: string } }): Promise<unknown>;
  delete(key: string): Promise<void>;
};

export type ImageBackend = "r2-binding" | "r2-s3" | "none";

export const DEFAULT_IMAGE_BASE = "https://images.vierapparatus.com";
export const IMMUTABLE_CACHE = "public, max-age=31536000, immutable";

/** The Worker's environment, if this code runs inside a Cloudflare Worker started by OpenNext. Read without importing the package, so Vercel builds do not need it. */
function cloudflareEnv(): Record<string, unknown> | undefined {
  const ctx = (globalThis as Record<symbol, unknown>)[Symbol.for("__cloudflare-context__")] as { env?: Record<string, unknown> } | undefined;
  return ctx?.env;
}

function binding(): R2BucketLike | null {
  const b = cloudflareEnv()?.IMAGES as R2BucketLike | undefined;
  return b && typeof b.put === "function" ? b : null;
}

type S3Config = { accountId: string; accessKeyId: string; secretAccessKey: string; bucket: string };

function s3Config(): S3Config | null {
  const accountId = process.env.R2_ACCOUNT_ID;
  const accessKeyId = process.env.R2_ACCESS_KEY_ID;
  const secretAccessKey = process.env.R2_SECRET_ACCESS_KEY;
  const bucket = process.env.R2_BUCKET;
  return accountId && accessKeyId && secretAccessKey && bucket ? { accountId, accessKeyId, secretAccessKey, bucket } : null;
}

export function imageBackend(): ImageBackend {
  if (binding()) return "r2-binding";
  if (s3Config()) return "r2-s3";
  return "none";
}

export function publicImageBase(): string {
  return (process.env.IMAGE_PUBLIC_BASE_URL || DEFAULT_IMAGE_BASE).replace(/\/+$/, "");
}

export const publicImageUrl = (key: string) => `${publicImageBase()}/${key}`;

/** Object keys are generated by the server, but are checked again so nothing odd can ever reach the bucket. */
const SAFE_KEY = /^(?:[a-z0-9]+\/)+[A-Za-z0-9_-]+\.webp$/;

function s3Url(c: S3Config, key: string): string {
  return `https://${c.accountId}.r2.cloudflarestorage.com/${c.bucket}/${key}`;
}

export async function putObject(key: string, bytes: Uint8Array, contentType = "image/webp"): Promise<void> {
  if (!SAFE_KEY.test(key)) throw new Error("Invalid image key.");
  const bound = binding();
  if (bound) {
    await bound.put(key, bytes, { httpMetadata: { contentType, cacheControl: IMMUTABLE_CACHE } });
    return;
  }
  const c = s3Config();
  if (!c) throw new Error("No image storage is configured.");
  const url = s3Url(c, key);
  const headers = await signRequest({
    method: "PUT",
    url,
    region: "auto",
    accessKeyId: c.accessKeyId,
    secretAccessKey: c.secretAccessKey,
    payload: bytes,
    headers: { "content-type": contentType, "cache-control": IMMUTABLE_CACHE },
  });
  const res = await fetch(url, { method: "PUT", headers, body: bytes as BodyInit });
  if (!res.ok) throw new Error(`Image storage refused the upload (HTTP ${res.status}).`);
}

export async function deleteObject(key: string): Promise<void> {
  if (!SAFE_KEY.test(key)) throw new Error("Invalid image key.");
  const bound = binding();
  if (bound) {
    await bound.delete(key);
    return;
  }
  const c = s3Config();
  if (!c) throw new Error("No image storage is configured.");
  const url = s3Url(c, key);
  const headers = await signRequest({ method: "DELETE", url, region: "auto", accessKeyId: c.accessKeyId, secretAccessKey: c.secretAccessKey });
  const res = await fetch(url, { method: "DELETE", headers });
  if (!res.ok && res.status !== 404) throw new Error(`Image storage refused the delete (HTTP ${res.status}).`);
}
